"""Phase B live re-baseline orchestrator.

Sweeps the leaderboard variant set across {model} × {thinking} × N seeds via
the new harness runner, then writes ``MIGRATION_REPORT.md`` with mean±std,
Welch-t vs the archived RESEARCH.md numbers, and a per-stage breakdown.

Resumable: each (variant, model, thinking, seed) writes to an append-only
result path; configs that already exist on disk are loaded, not re-run.

Usage::

    # Smoke (one variant, all 4 configs, N=3 — ~2.8k API calls)
    python -m experiments.analysis.validate_migration --variants hybrid

    # Full sweep (8 variants × 4 configs × N=3 — ~28k API calls)
    python -m experiments.analysis.validate_migration --full
"""

from __future__ import annotations

import argparse
import asyncio
import itertools
import json
import logging
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from benchmark.ground_truth import GroundTruth  # noqa: E402
from benchmark.stats import RunSet, welch_t  # noqa: E402
from benchmark.testset import OfflineTestset  # noqa: E402
from gently_perception.render import CachedFrameSource  # noqa: E402
from experiments.harness.config import RunConfig  # noqa: E402
from experiments.harness.discover import discover_variants  # noqa: E402
from experiments.harness.events import EventLog  # noqa: E402
from experiments.harness.loop import run_variant  # noqa: E402
from experiments.harness.model_override import install_model_override  # noqa: E402
from experiments.harness.run import _load_references  # noqa: E402

logger = logging.getLogger(__name__)

DATA_DIR = REPO_ROOT / "data"
RESULTS_DIR = DATA_DIR / "results"
REPORT_PATH = REPO_ROOT / "MIGRATION_REPORT.md"

LEADERBOARD = ["hybrid", "scientific", "temporal", "multimeasure",
               "vote3_mm", "fillpct", "ensemble", "minimal"]
MODELS = ["claude-opus-4-6", "claude-opus-4-7"]
THINKING = [None, "adaptive"]
STAGES = ("1.5fold", "2fold", "pretzel")

# Archived baselines from RESEARCH.md for Welch-t comparison.
ARCHIVED: dict[str, tuple[float, float, int]] = {
    # name → (mean, std, N)
    "hybrid@claude-opus-4-6/none": (0.817, 0.024, 3),
    "vote3_mm@claude-opus-4-7/adaptive": (0.808, 0.005, 3),
    "multimeasure@claude-opus-4-7/adaptive": (0.803, 0.048, 3),
    "fillpct@claude-opus-4-6/none": (0.775, 0.046, 3),
    "fillpct@claude-opus-4-7/adaptive": (0.761, 0.047, 5),
}


async def run_one_config(variant: str, model: str, thinking: str | None,
                         n_runs: int, testset, references) -> list[dict]:
    """Run N seeds of one (variant, model, thinking). Resumable."""
    perceive = discover_variants()[variant]
    reports: list[dict] = []
    for seed in range(n_runs):
        cfg = RunConfig.capture(variant=variant, model=model, thinking=thinking,
                                seed=seed, stages=STAGES)
        out = cfg.result_path(RESULTS_DIR)
        if out.exists():
            logger.info(f"  [cached] {variant}@{model}/{thinking or 'none'} seed={seed}")
            reports.append(json.loads(out.read_text()))
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        ev = EventLog(out.with_suffix(".events.jsonl"))
        logger.info(f"  [run] {variant}@{model}/{thinking or 'none'} seed={seed}")
        with install_model_override(model, thinking):
            r = await run_variant(perceive, testset, references, cfg,
                                  event_log=ev, concurrency=3)
        ev.close()
        out.write_text(json.dumps(r, indent=2, default=str))
        reports.append(r)
    return reports


def write_report(results: dict[tuple[str, str, str | None], RunSet]) -> None:
    lines = [
        "# Migration Report — Phase B live re-baseline",
        "",
        f"Generated by `validate_migration.py`. Stages: {'+'.join(STAGES)}, "
        f"n=233 frames (embryos 1–3).",
        "",
        "## Leaderboard (new harness)",
        "",
        "| Variant | Model | Thinking | mean ± std | N | vs archived |",
        "|---|---|---|---|---|---|",
    ]
    for (variant, model, thinking), rs in sorted(results.items()):
        key = f"{variant}@{model}/{thinking or 'none'}"
        cmp_cell = "—"
        if key in ARCHIVED:
            am, asd, an = ARCHIVED[key]
            arch = RunSet(f"arch:{key}", tuple(
                am + (i - (an - 1) / 2) * (asd / max(an - 1, 1))
                for i in range(an)
            ))
            try:
                t = welch_t(rs, arch).t
                flag = "⚠" if abs(t) > 2 else "✓"
                cmp_cell = f"{100*am:.1f}±{100*asd:.1f} (t={t:.2f}) {flag}"
            except ValueError:
                cmp_cell = f"{100*am:.1f}±{100*asd:.1f}"
        lines.append(
            f"| {variant} | {model} | {thinking or 'none'} | "
            f"{rs.mean_std_pct()} | {rs.n} | {cmp_cell} |"
        )
    lines += [
        "",
        "## Pass criteria",
        "",
        "- **No accuracy regression**: hybrid@opus-4-6/none mean within "
        "[77, 86] (81.7 ± 2σ from RESEARCH.md).",
        "- **Provenance**: every result JSON has full config (model, thinking, "
        "git_sha, seed) — verified by construction.",
        "",
    ]
    REPORT_PATH.write_text("\n".join(lines))
    print(f"\nWrote {REPORT_PATH}")


async def main() -> None:
    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s %(levelname)s %(message)s")
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--variants", nargs="+", default=["hybrid"],
                   help=f"variants to sweep (or --full). leaderboard: {LEADERBOARD}")
    p.add_argument("--full", action="store_true",
                   help="sweep all 8 leaderboard variants")
    p.add_argument("--models", nargs="+", default=MODELS)
    p.add_argument("--thinking", nargs="+", default=["none", "adaptive"])
    p.add_argument("--n-runs", type=int, default=3)
    args = p.parse_args()

    variants = LEADERBOARD if args.full else args.variants
    thinking_vals = [None if t == "none" else t for t in args.thinking]

    gt = GroundTruth.from_json(DATA_DIR / "ground_truth" / "59799c78.json")
    testset = CachedFrameSource(
        OfflineTestset(session_path=DATA_DIR / "volumes", ground_truth=gt,
                       load_volumes=True),
        cache_dir=DATA_DIR / "cache" / "frames",
    )
    refs = _load_references()

    results: dict[tuple[str, str, str | None], RunSet] = {}
    configs = list(itertools.product(variants, args.models, thinking_vals))
    print(f"Sweeping {len(configs)} configs × N={args.n_runs} "
          f"= {len(configs) * args.n_runs} runs")

    for variant, model, thinking in configs:
        reports = await run_one_config(variant, model, thinking, args.n_runs,
                                       testset, refs)
        rs = RunSet.from_reports(f"{variant}@{model}/{thinking or 'none'}", reports)
        results[(variant, model, thinking)] = rs
        print(f"  {rs.name}: {rs.mean_std_pct()}")

    write_report(results)
    print(f"render cache: {testset.stats()}")


if __name__ == "__main__":
    asyncio.run(main())
